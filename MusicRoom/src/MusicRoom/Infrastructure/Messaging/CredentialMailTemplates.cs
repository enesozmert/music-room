using System.Globalization;
using System.Net;
using MusicRoom.Application.Abstractions.Messaging;

namespace MusicRoom.Infrastructure.Messaging;

/// <summary>
/// Builds the three messages: the words from <see cref="MailCopyBook" />, the layout from
/// <see cref="MailTemplateRenderer" /> — SPEC-024 decision 5, SPEC-052.
/// </summary>
/// <remarks>
/// **Public, like this project's other adapters**, because what a reader receives is asserted by tests —
/// the language, the code as text, the palette and the absence of an unrendered placeholder.
/// <para>
/// **Every value is HTML-encoded on the way in.** The code and the token are generated by this application
/// and are URL-safe, and a display name is not: it is whatever somebody typed at registration. A body that
/// interpolates one value without encoding is a body that will one day interpolate another —
/// `application-security`.
/// </para>
/// <para>
/// **The code is text, not an image and not a colour.** A screen reader has to be able to read it out, and
/// a reader who cannot distinguish the accent from the background still has to find it — which is also why
/// it carries a label rather than standing alone.
/// </para>
/// </remarks>
public static class CredentialMailTemplates
{
    /// <summary>Builds the verification message.</summary>
    /// <param name="message">The recipient, the language, the token and the code.</param>
    /// <param name="linkBaseUrl">Where the client serves the verification screen, or null.</param>
    /// <returns>The subject and both bodies.</returns>
    public static RenderedMail Verification(VerificationMail message, string? linkBaseUrl)
    {
        ArgumentNullException.ThrowIfNull(message);

        MailCopy copy = MailCopyBook.Verification(message.Language, message.DisplayName);
        string? link = Link(linkBaseUrl, message.Token);

        // A code is always there; the button only when a link base is configured, for the reason the
        // Development sender gives — a link pointing at a machine nobody intended is worse than no link.
        return Render(
            copy,
            message.Language,
            CodeBlock(message.Language, message.Code) + Action(copy, link) + Validity(copy),
            CodeText(message.Language, message.Code) + ActionText(copy, link) + ValidityText(copy));
    }

    /// <summary>Builds the password reset message — a link, and deliberately no code.</summary>
    /// <param name="message">The recipient, the language and the token.</param>
    /// <param name="linkBaseUrl">Where the client serves the reset screen, or null.</param>
    /// <returns>The subject and both bodies.</returns>
    public static RenderedMail Reset(PasswordResetMail message, string? linkBaseUrl)
    {
        ArgumentNullException.ThrowIfNull(message);

        MailCopy copy = MailCopyBook.Reset(message.Language, message.DisplayName);
        string? link = Link(linkBaseUrl, message.Token);

        // No link configured means the bare token, as it always has: the flow still completes through the
        // API, and a link pointing at a machine nobody intended is worse than no link.
        string html = link is null
            ? CodeBlock(message.Language, message.Token) + Validity(copy)
            : Action(copy, link) + Validity(copy);

        string text = link is null
            ? CodeText(message.Language, message.Token) + ValidityText(copy)
            : ActionText(copy, link) + ValidityText(copy);

        return Render(copy, message.Language, html, text);
    }

    /// <summary>Builds the welcome message.</summary>
    /// <param name="message">The recipient and the language.</param>
    /// <param name="appUrl">Where the product lives, or null when nothing configured it.</param>
    /// <returns>The subject and both bodies.</returns>
    public static RenderedMail Welcome(WelcomeMail message, string? appUrl)
    {
        ArgumentNullException.ThrowIfNull(message);

        MailCopy copy = MailCopyBook.Welcome(message.Language, message.DisplayName);

        return Render(copy, message.Language, Action(copy, appUrl), ActionText(copy, appUrl));
    }

    /// <summary>The code, large and spaced, with a label a screen reader announces first.</summary>
    private static string CodeBlock(MailLanguage language, string code) =>
        $"""
         <p class="muted" style="margin:0 0 8px; font-size:14px; line-height:1.5; color:#444444;">
           {Label(language)}
         </p>
         <p class="code"
            style="margin:0 0 28px; padding:20px 24px; background:#f4f4f4; border:1px solid #e0e0e0;
                   border-radius:12px; font-family:'SFMono-Regular',Consolas,'Liberation Mono',monospace;
                   font-size:32px; letter-spacing:8px; font-weight:700; text-align:center; color:#000000;">
           {WebUtility.HtmlEncode(code)}
         </p>
         """;

    private static string CodeText(MailLanguage language, string code) =>
        $"{Label(language)}\n\n    {code}\n\n";

    private static string Label(MailLanguage language) =>
        language == MailLanguage.Turkish ? "Doğrulama kodun" : "Your verification code";

    /// <summary>
    /// The button, and the same URL in text beneath it.
    /// </summary>
    /// <remarks>
    /// 44 pixels of height and 16 pixels of text: a target a thumb can hit and type a reader does not have
    /// to zoom into. The URL is repeated as text because a client that strips the button must still leave
    /// a way through, and because a reader deciding whether to click is entitled to see where it goes.
    /// </remarks>
    private static string Action(MailCopy copy, string? link)
    {
        if (link is null)
        {
            return string.Empty;
        }

        string safe = WebUtility.HtmlEncode(link);

        return $"""
                <p style="margin:0 0 20px;">
                  <a class="action" href="{safe}"
                     style="display:inline-block; padding:14px 28px; min-height:44px; box-sizing:border-box;
                            background:#000000; color:#ffffff; font-size:16px; font-weight:600;
                            text-decoration:none; border-radius:10px;">{WebUtility.HtmlEncode(copy.CallToAction)}</a>
                </p>
                <p class="muted" style="margin:0 0 28px; font-size:13px; line-height:1.6; color:#6b6b6b;
                                        word-break:break-all;">{safe}</p>
                """;
    }

    private static string ActionText(MailCopy copy, string? link) =>
        link is null ? string.Empty : $"{copy.CallToAction}: {link}\n\n";

    private static string Validity(MailCopy copy) =>
        string.IsNullOrEmpty(copy.Validity)
            ? string.Empty
            : $"""<p class="muted" style="margin:0; font-size:14px; line-height:1.6; color:#444444;">{WebUtility.HtmlEncode(copy.Validity)}</p>""";

    private static string ValidityText(MailCopy copy) =>
        string.IsNullOrEmpty(copy.Validity) ? string.Empty : copy.Validity + "\n";

    /// <summary>Appends the token to the configured base, or returns null when nothing configured one.</summary>
    private static string? Link(string? baseUrl, string token) =>
        string.IsNullOrWhiteSpace(baseUrl)
            ? null
            : string.Create(
                CultureInfo.InvariantCulture,
                $"{baseUrl.TrimEnd('/')}?token={Uri.EscapeDataString(token)}");

    private static RenderedMail Render(MailCopy copy, MailLanguage language, string html, string text)
    {
        MailBody body = MailTemplateRenderer.Render(new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["lang"] = language == MailLanguage.Turkish ? "tr" : "en",
            ["subject"] = WebUtility.HtmlEncode(copy.Subject),
            ["preheader"] = WebUtility.HtmlEncode(copy.Preheader),
            ["heading"] = WebUtility.HtmlEncode(copy.Heading),
            ["greeting"] = WebUtility.HtmlEncode(copy.Greeting),
            ["explanation"] = WebUtility.HtmlEncode(copy.Explanation),
            ["footer"] = WebUtility.HtmlEncode(copy.Footer),
            ["body"] = html,
        });

        // The text part takes the same words unencoded: it is read as text, and `&#39;` in a plain-text
        // mail is the kind of detail that makes a product look unfinished.
        MailBody plain = new(
            body.Html,
            body.Text
                .Replace("{{heading}}", copy.Heading, StringComparison.Ordinal)
                .Replace("{{greeting}}", copy.Greeting, StringComparison.Ordinal)
                .Replace("{{explanation}}", copy.Explanation, StringComparison.Ordinal)
                .Replace("{{footer}}", copy.Footer, StringComparison.Ordinal)
                .Replace("{{body}}", text, StringComparison.Ordinal));

        return new RenderedMail(copy.Subject, plain.Html, plain.Text);
    }
}

/// <summary>
/// A message, ready to hand to a transport.
/// </summary>
/// <param name="Subject">The subject line, in the reader's language.</param>
/// <param name="Html">The HTML body.</param>
/// <param name="Text">The plain-text body, for a client that refuses HTML.</param>
public sealed record RenderedMail(string Subject, string Html, string Text);
