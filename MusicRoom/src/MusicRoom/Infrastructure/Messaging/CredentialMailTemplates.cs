using System.Globalization;
using System.Net;

namespace MusicRoom.Infrastructure.Messaging;

/// <summary>
/// What the two credential messages say — SPEC-024 decision 5.
/// </summary>
/// <remarks>
/// Composed here rather than in a provider template, so the words a user receives are reviewable in the same
/// diff as the code that sends them. A template id in a vendor dashboard is text nobody on this project reads
/// again.
/// <para>
/// Every message carries the token and nothing else personal — ADR-0013. No display name, no account id, no
/// address beyond the recipient header the provider needs.
/// </para>
/// </remarks>
internal static class CredentialMailTemplates
{
    // Constants are internal rather than private because the .editorconfig naming rule asks a private field
    // for an underscore prefix, and a const is a field to that rule.

    /// <summary>The subject of the verification message.</summary>
    internal const string VerificationSubject = "Confirm your Music Room address";

    /// <summary>The subject of the reset message.</summary>
    internal const string ResetSubject = "Reset your Music Room password";

    /// <summary>How long a reader has, in words. The numbers themselves are SPEC-003's and SPEC-007's.</summary>
    internal const string VerificationValidity = "This link is valid for 24 hours and can be used once.";

    /// <summary>The same sentence for the shorter-lived reset token.</summary>
    internal const string ResetValidity = "This link is valid for 1 hour and can be used once.";

    /// <summary>Builds the verification message.</summary>
    /// <param name="token">The plaintext token. It appears in the link and nowhere else.</param>
    /// <param name="linkBaseUrl">Where the client serves the verification screen, or null.</param>
    /// <returns>The HTML and text bodies.</returns>
    internal static MailBody Verification(string token, string? linkBaseUrl) =>
        Build(new MailCopy(
            Heading: "Confirm your address",
            Explanation: "Someone registered this address with Music Room. Confirm it to finish signing up.",
            CallToAction: "Confirm address",
            Validity: VerificationValidity,
            Link: Link(linkBaseUrl, token),
            Token: token));

    /// <summary>Builds the password reset message.</summary>
    /// <param name="token">The plaintext token. It appears in the link and nowhere else.</param>
    /// <param name="linkBaseUrl">Where the client serves the reset screen, or null.</param>
    /// <returns>The HTML and text bodies.</returns>
    internal static MailBody Reset(string token, string? linkBaseUrl) =>
        Build(new MailCopy(
            Heading: "Reset your password",
            Explanation: "Someone asked to reset the credentials for this address. If it was not you, "
                + "ignore this message and nothing changes.",
            CallToAction: "Choose a new password",
            Validity: ResetValidity,
            Link: Link(linkBaseUrl, token),
            Token: token));

    /// <summary>
    /// Appends the token to the configured base, or returns null when nothing configured one.
    /// </summary>
    /// <remarks>
    /// No default base URL, for the reason <see cref="LoggingMailService"/> gives: a link pointing at a
    /// machine nobody intended is worse than no link. Without a base the message carries the bare token and
    /// says what to do with it, which still completes the flow through the API.
    /// </remarks>
    private static string? Link(string? baseUrl, string token) =>
        string.IsNullOrWhiteSpace(baseUrl)
            ? null
            : string.Create(
                CultureInfo.InvariantCulture,
                $"{baseUrl.TrimEnd('/')}?token={Uri.EscapeDataString(token)}");

    private static MailBody Build(MailCopy copy)
    {
        // Encoded on the way into the HTML body. The token is generated by this application and is URL-safe,
        // but a body that interpolates a value without encoding it is a body that will one day interpolate
        // something else — `application-security`.
        string safeLink = copy.Link is null ? string.Empty : WebUtility.HtmlEncode(copy.Link);
        string safeToken = WebUtility.HtmlEncode(copy.Token);

        string action = copy.Link is null
            ? $"<p>Your code is <code>{safeToken}</code>.</p>"
            : $"<p><a href=\"{safeLink}\">{copy.CallToAction}</a></p><p>Or paste this link: {safeLink}</p>";

        string textAction = copy.Link is null
            ? $"Your code is: {copy.Token}"
            : $"{copy.CallToAction}: {copy.Link}";

        return new MailBody(
            $"<h1>{copy.Heading}</h1><p>{copy.Explanation}</p>{action}<p>{copy.Validity}</p>",
            $"{copy.Heading}\n\n{copy.Explanation}\n\n{textAction}\n\n{copy.Validity}\n");
    }
}

/// <summary>
/// One message's words, before they are rendered.
/// </summary>
/// <param name="Heading">The first line of the body.</param>
/// <param name="Explanation">Why the reader received this.</param>
/// <param name="CallToAction">The link text.</param>
/// <param name="Validity">How long the token lasts, in words.</param>
/// <param name="Link">The composed link, or null when no base URL is configured.</param>
/// <param name="Token">The plaintext token, used when there is no link to wrap it in.</param>
/// <remarks>
/// A record rather than six arguments: `SonarLint.xml` allows five (S107), and the six values belong together
/// anyway — they are one message.
/// </remarks>
internal sealed record MailCopy(
    string Heading,
    string Explanation,
    string CallToAction,
    string Validity,
    string? Link,
    string Token);

/// <summary>
/// One message's two representations.
/// </summary>
/// <param name="Html">The HTML body.</param>
/// <param name="Text">The plain-text body, for a client that will not render HTML.</param>
internal sealed record MailBody(string Html, string Text);
